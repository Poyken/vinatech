				A.SIZE,
				SUM(A.TOTALQTY) AS TOTALOUT
				INTO #T1
		FROM
				STB_VN_MASTERMODULES A

				
	WHERE

				 TYPEEXPORT = N'Xuất' AND ISUSED = '1' AND TOTALQTY IS NOT NULL AND DIVIDETHENUMBER IS NOT NULL
				 GROUP BY PARTNO,SIZE


SELECT

				  PARTNO, SUM(TOTALQTY) AS TOTALIMPORT
				  INTO #T2
			FROM

				 STB_VN_MASTERMODULES WITH(NOLOCK)

				 

			WHERE

				 TYPEIMPORT = N'Nhập' AND ISUSED = '1' AND TOTALQTY IS NOT NULL AND DIVIDETHENUMBER IS NOT NULL

			GROUP BY PARTNO


		SELECT
				#T1.PARTNO,
				#T1.SIZE,
				SUM(#T1.TOTALOUT) AS TOTALOUT,
				SUM(#T2.TOTALIMPORT) AS TOTALIMPORT,
				SUM(#T1.TOTALOUT - #T2.TOTALIMPORT) AS 'INVENTORY'

				INTO #T3
		FROM
			 #T1

			LEFT JOIN #T2
			ON #T2.PARTNO = #T1.PARTNO

			GROUP BY #T1.PARTNO,#T1.SIZE


