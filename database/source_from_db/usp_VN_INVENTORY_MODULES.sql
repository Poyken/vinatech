				 PARTNO,
				 SIZE,
				 TOTALOUT,
				 TOTALIMPORT,
				 INVENTORY,
				 CASE
					WHEN TOTALIMPORT IS NULL THEN TOTALOUT
					ELSE INVENTORY
				END AS Result
						
			FROM
				#T3

		DROP TABLE #T1
		DROP TABLE #T2
		DROP TABLE #T3
