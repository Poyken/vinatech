CREATE PROC [dbo].[usp_vn_loginfinishgood_web]
@pUSERID NVARCHAR(50),
@pASSWORDS NVARCHAR(100),
@pCODE NVARCHAR(50)
AS
BEGIN

		SELECT
				USERID,
				PASSWORDS,
				FULLNAME,
				CODECOMPANY
		FROM
			STB_VN_USER_FINISHGOOD WITH (NOLOCK)

		WHERE
				
				USERID = @pUSERID
				AND
				PASSWORDS = @pASSWORDS 
				AND 
				IsUse = 1

END
