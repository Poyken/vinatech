$bcList = "'" + ($barcodes -join "','") + "'"

$query = @"
SELECT 
    SI.Barcode,
    SI.InputLineCode,
    SI.MaterialCode,
    SUM(CASE WHEN PRH.RouteCode LIKE '%_HY' THEN 1 ELSE 0 END) AS Count_HY_Routes,
    SUM(CASE WHEN PRH.RouteCode LIKE '%_BG' THEN 1 ELSE 0 END) AS Count_BG_Routes
FROM STB_SetInfo SI
LEFT JOIN STB_ProdRouteHist PRH ON PRH.ControlNo = SI.ControlNo AND PRH.RouteCode IN ('V-26_BG', 'V-27_BG', 'V-28_BG', 'V-26_HY', 'V-27_HY', 'V-28_HY')
WHERE SI.Barcode IN ($bcList)
GROUP BY SI.Barcode, SI.InputLineCode, SI.MaterialCode
ORDER BY SI.Barcode;
"@

& .\MES_V2\cli\mes.ps1 query $query -Format Table
